const originalSpanish = new Map();
document.querySelectorAll("[data-i18n]").forEach((element) => originalSpanish.set(element, element.innerHTML));

function setLanguage(language) {
  const dictionary = translations[language] || {};
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.innerHTML = dictionary[element.dataset.i18n] || originalSpanish.get(element);
  });
  document.documentElement.lang = language;
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });
  const menuToggle = document.querySelector(".menu-toggle");
  if (menuToggle) menuToggle.setAttribute("aria-label", dictionary.menuOpen || "Abrir menú");
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

const menuToggle = document.querySelector(".menu-toggle");
const mainNav = document.querySelector(".main-nav");
menuToggle?.addEventListener("click", () => {
  const open = menuToggle.getAttribute("aria-expanded") !== "true";
  menuToggle.setAttribute("aria-expanded", String(open));
  mainNav?.classList.toggle("is-open", open);
});
mainNav?.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
  mainNav.classList.remove("is-open");
  menuToggle?.setAttribute("aria-expanded", "false");
}));
document.querySelector("#year").textContent = new Date().getFullYear();
